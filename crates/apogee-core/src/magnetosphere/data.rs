/// Linear interpolation of coefficients from the 2020.0 epoch using the
/// 2020-2025 secular variation values.
///
/// `decimal_year` is the epoch in fractional years (e.g. 2024.5). Coefficients
/// are clipped to the IGRF-13 validity interval for robustness, though the
/// model is intended for 2020-2025.
pub(crate) fn coefficients_at_epoch(
    decimal_year: f64,
) -> ([f64; IGRF_COEFF_LEN], [f64; IGRF_COEFF_LEN]) {
    // Clamp to a generous interval around the IGRF-13 generation.
    let year = decimal_year.clamp(2015.0, 2030.0);
    let dt = year - 2020.0;
    let mut g = [0.0; IGRF_COEFF_LEN];
    let mut h = [0.0; IGRF_COEFF_LEN];
    for i in 0..IGRF_COEFF_LEN {
        g[i] = G_2020[i] + dt * G_SV_2020[i];
        h[i] = H_2020[i] + dt * H_SV_2020[i];
    }
    (g, h)
}
